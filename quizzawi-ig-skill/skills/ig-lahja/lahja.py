#!/usr/bin/env python3
"""فاحص اللهجة الأردنية لنصوص الفويس. الاستخدام: python3 lahja.py text.txt
بيلقط كلمات شامية/لبنانية/فصحى وقواعد القناة (ق بتضل ق، الثاء بالأرقام، الضمائر بالميم، اسم القناة)."""
import sys, re
SWAP = {  # كلمة غلط: البديل الأردني
 "هلّق":"هسّة","هلق":"هسّة","هلأ":"هسّة","هلا":"(ترحيب ممنوع)","مو ":"مِش ","موش":"مِش","كتير":"كْثِير","هيك":"هيك (تمام)",
 "تلات":"ثلاث","تلاتة":"ثلاثة","تمانية":"ثمانية","اتنين":"اثنين","تنين":"اثنين","تلت":"ثُلُث",
 "عم ":"(قاعد/بـ) بدل «عم»","لسا":"لسا (تمام)","كرمال":"عشان","منيح":"زاكي/تمام","شوي":"شوي (تمام)","دغري":"على طول","ليك":"شوف",
 "هلقد":"هالقد","هيدا":"هاد","هيدي":"هاي","كيف حالكم":"كيفكم","أهلين فيكم":"(ترحيب ممنوع)","اهلين فيكم":"(ترحيب ممنوع)",
 "لازم تلاقي":"لازم تلاقي (تمام)","وين":"وين (تمام)",
}
SKIP = {k for k,v in SWAP.items() if "تمام" in v}
RULES = [
 (r"[گئ]","ممنوع «گ» و«ئ»: القاف بتنكتب «ق»."),
 (r"(?<![ا-ي])Quizzawi","اسم القناة بالفويس «كْوِيز زَاوِي» (بالشاشة Quizzawi)."),
 (r"\b(?:واحِد)\b","وَاحَد مش وَاحِد."),
 (r"[ًٌٍ]","تنوين/إعراب: ممنوع إلا «أَبَداً»."),
 (r"خمسطعش|خمسة عشر","خَمِسْطَعْشَ."),
 (r"ستة عشر","سِطَّعِش."),
 (r"فيكم(?!ُ?م)","الضمير بالميم: فِيكُمْ."),
]
def main():
    t=open(sys.argv[1],encoding="utf-8").read() if len(sys.argv)>1 else sys.stdin.read()
    # أبداً بالتنوين مسموحة
    t2=t.replace("أَبَداً","")
    found=0
    for ln,line in enumerate(t2.splitlines(),1):
        for w,alt in SWAP.items():
            if w in line and w not in SKIP and "تمام" not in alt:
                print(f"سطر {ln}: «{w.strip()}» → {alt}"); found+=1
        for rx,msg in RULES:
            if re.search(rx,line): print(f"سطر {ln}: {msg}"); found+=1
    print("\n"+("ما لقيت مشاكل." if not found else f"{found} ملاحظة."))
if __name__=="__main__": main()
